def synthetic_layout(start: np.ndarray = THETA_TRUE) -> ParameterLayout:
    s = [float(v) for v in start]
    return ParameterLayout([
        ParameterSpec("sigma_x1", "taste", "x1", "nu0", s[0], 0.0, 50.0),
        ParameterSpec("sigma_x2", "taste", "x2", "nu1", s[1], 0.0, 50.0, unit=1.0),
        ParameterSpec("pi_x1_demo", "taste", "x1", "demo", s[2], -math.inf, math.inf),
        ParameterSpec("phi_inc", "scale", None, "inc", s[3], -math.inf, math.inf),
        ParameterSpec("sigma_p", "sigma_p", None, None, s[4], 0.05, 3.0),
    ])


def _instruments(products: dict[str, np.ndarray]) -> tuple[np.ndarray, np.ndarray]:
    mk, x1, x2, p = (products[c] for c in ("market_ids", "x1", "x2", "prices"))
    rival_x1 = np.array([x1[mk == m].sum() for m in mk]) - x1
    X1 = np.column_stack([np.ones(mk.size), x1, x2])
    Z = np.column_stack([X1, p, p**2, rival_x1, x1 * x2, x1 * p])
    return X1, Z


def make_synthetic(n_markets: int, J0: int, A: int, nu_per_agent: int, seed: int = 7,
                   theta: np.ndarray = THETA_TRUE, min_share: float = 1e-4, price_shift: float = 0.0,
                   delta_shift: float = 0.0) -> dict[str, Any]:
    """Products and agents frames (dicts of arrays) whose shares the model generated at theta.

    Products sit at random angles on the unit circle in (x1, x2), so with taste spreads on both
    columns most of them are some consumer's favourite. Each market starts with J0 candidates;
    products whose share falls below ``min_share`` (never on a frontier, or almost) are dropped and
    xi re-orthogonalised to the new Z until every share is above it. ``price_shift`` adds a constant to
    every price and ``delta_shift`` to every delta (the supply tests use them to get positive Nash costs).
    """
    rng = np.random.default_rng(seed)
    n = n_markets * J0
    mk = np.repeat(np.arange(1, n_markets + 1), J0)[rng.permutation(n)]  # rows unsorted: the adapter sorts
    a = rng.uniform(0.0, 2.0 * np.pi, n)
    x1, x2 = np.cos(a), np.sin(a)
    p = break_price_ties(2.0 + price_shift + rng.uniform(0.0, 4.0, n) + (1.0 + x1), mk, 0.01)
    e = rng.normal(0.0, 0.3, n)
    am = np.repeat(np.arange(1, n_markets + 1), A)
    inc = rng.normal(0.0, 0.5, am.size)
    agents = {"market_ids": am, "weights": np.full(am.size, 1.0 / A),
              "demo": rng.integers(1, 6, am.size).astype(float), "inc": inc, "hi": (inc > 0).astype(float)}
    keep = np.arange(n)
    for _ in range(50):
        products = {"market_ids": mk[keep], "prices": p[keep], "x1": x1[keep], "x2": x2[keep],
                    "top": (x1[keep] > 0).astype(float), "shares": np.full(keep.size, 0.01)}
        X1, Z = _instruments(products)
        xi = e[keep] - Z @ np.linalg.lstsq(Z, e[keep], rcond=None)[0]
        delta = X1 @ BETA_TRUE + delta_shift + xi
        data = {"products": products, "agents": agents}
        model = PCMModel(PCMSpec(CHARS), data, synthetic_layout(), nu_per_agent, seed, total_threads=4)
        th, ph, sp = model.kernel_params(theta)
        s = np.empty(keep.size)
        for t, m in enumerate(model.markets):
            s[m.rows] = pcm_kernel.evaluate_market(delta[m.rows], model.kernel_market(t), th, ph, sp,
                                                   derivatives=False)["s"]
        model.close()
        if s.min() > min_share:
            break
        keep = keep[s > min_share]
    else:
        raise AssertionError("synthetic data: pruning did not settle")
    products["shares"] = s
    return {"data": data, "delta": delta, "xi": xi, "X1": X1, "Z": Z, "nu": nu_per_agent, "seed": seed,
            "J": np.bincount(np.unique(products["market_ids"], return_inverse=True)[1])}


def micro_parts() -> tuple[list[MicroPart], list[MicroPart], list[str]]:
    top = MicroPart("top", (), ("top",))
    demo_top = MicroPart("demo*top", ("demo",), ("top",))
    hi_in = MicroPart("hi_inside", ("hi",), ())
    hi = MicroPart("hi", ("hi",), (), outside_value=1.0)
    inc_in = MicroPart("inc_inside", ("inc",), ())
    inside = MicroPart("inside", (), ())
    return ([demo_top, hi_in, inc_in], [top, hi, inside], ["E[demo|top]", "E[inside|hi]", "E[inc|inside]"])


def build_problem(syn: dict[str, Any], start: np.ndarray, threads: int = 8, micro_values: np.ndarray | None = None,
                  **spec_kw: Any) -> NFPGMMProblem:
    spec = PCMSpec(CHARS, **({"tol": 1e-12} | spec_kw))
    layout = synthetic_layout(start)
    model = PCMModel(spec, syn["data"], layout, syn["nu"], syn["seed"], total_threads=threads)
    nums, dens, labels = micro_parts()
    if micro_values is None:
        micro_values = true_micro_values(syn)
    micro = RatioMicroMoment("micro", MicroDataset("synthetic", 10_000), nums, dens, micro_values, labels)
    return NFPGMMProblem(model, [IVMoments(syn["Z"]), micro], LinearIV(syn["X1"], syn["Z"]), layout)


_MICRO_CACHE: dict[int, np.ndarray] = {}


def true_micro_values(syn: dict[str, Any]) -> np.ndarray:
    key = id(syn)
    if key not in _MICRO_CACHE:
        prob = build_problem(syn, THETA_TRUE, micro_values=np.zeros(3))
        ev = prob.evaluate(THETA_TRUE, need_jacobian=False)
        assert ev.ok, ev.status
        _MICRO_CACHE[key] = ev.aux["micro_predicted"]["micro"].copy()
        prob.model.close()
    return _MICRO_CACHE[key]


