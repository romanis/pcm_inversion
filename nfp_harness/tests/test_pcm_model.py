def test_draws_and_markets(small: dict[str, Any]) -> None:
    """Powers-of-two Sobol draws crossed with agents, agent weights preserved, products price-sorted."""
    model = PCMModel(PCMSpec(CHARS), small["data"], synthetic_layout(), 8, 2, total_threads=2)
    prods, agents = small["data"]["products"], small["data"]["agents"]
    assert model.n_products == 16 and len(model.markets) == 2
    for t, m in enumerate(model.markets):
        km = model.kernel_market(t)
        assert np.all(np.diff(km.p) > 0)
        np.testing.assert_array_equal(km.p, prods["prices"][m.rows])
        assert np.all(prods["market_ids"][m.rows] == m.market_id)
        R = km.weights.size
        assert R == 256 and R & (R - 1) == 0
        np.testing.assert_allclose(km.weights.sum(), agents["weights"][agents["market_ids"] == m.market_id].sum())
        nu = km.taste_basis[:, :2]
        assert abs(nu.mean()) < 0.05 and abs(nu.std() - 1.0) < 0.05
        draws = model.market_draws(t)
        demo = agents["demo"][draws["agent_rows"]][draws["agent_of_draw"]]
        np.testing.assert_array_equal(km.taste_basis[:, 2], demo)
        assert km.taste_col == [1, 2, 1]
    # automatic units resolved from the data: 1 / sd(x1), explicit 1, 1 / (sd(d) sd(demo)), 1 / sd(inc), 0.1
    u = model.layout.units()
    x1 = prods["x1"]
    assert u[0] == pytest.approx(1.0 / x1.std()) and u[1] == 1.0 and u[4] == 0.1
    model.close()


def test_status_not_exception(small: dict[str, Any]) -> None:
    """A singular ds/ddelta and a failed inversion are named statuses, never exceptions."""
    prob = build_problem(small, THETA_TRUE, rcond_min=0.5)
    ev = prob.evaluate(THETA_TRUE)
    assert ev.status is EvalStatus.SINGULAR_INNER_JACOBIAN and ev.G is None
    assert any(pm["kernel_status"] == "singular_ds_ddelta" for pm in ev.aux["per_market"])
    prob.model.close()
    prob = build_problem(small, THETA_TRUE, cold_evals=1, tol=1e-15)
    ev = prob.evaluate(THETA_TRUE + np.array([0.5, 0.5, 0.0, 0.0, 0.3]))
    assert ev.status is EvalStatus.INVERSION_FAILED
    prob.model.close()


def test_commit_restore_and_state(small: dict[str, Any]) -> None:
    """Trial points never overwrite the accepted warm start; commit promotes; state survives a reload."""
    prob = build_problem(small, THETA_TRUE)
    model: PCMModel = prob.model
    theta1 = THETA_TRUE + np.array([0.1, -0.1, 0.05, 0.1, 0.05])
    ev0 = prob.evaluate(THETA_TRUE)
    assert ev0.ok and model.accepted_delta() is None
    prob.commit(THETA_TRUE)
    acc = model.accepted_delta()
    np.testing.assert_allclose(acc, small["delta"], atol=1e-9)
    ev1 = prob.evaluate(theta1)
    assert ev1.ok
    prob.restore(theta1)
    np.testing.assert_array_equal(model.accepted_delta(), acc)
    ev1 = prob.evaluate(theta1)
    assert "realised_mass" in ev1.aux and 0.0 <= ev1.aux["realised_mass"] <= 1.0
    assert ev1.aux["realised_mass"] == model.realised_mass(theta1)
    prob.commit(theta1)
    np.testing.assert_array_equal(model.accepted_delta(), ev1.aux["delta"])
    state = prob.state_dict()
    fresh = build_problem(small, THETA_TRUE)
    fresh.load_state_dict(state)
    np.testing.assert_array_equal(fresh.model.accepted_delta(), ev1.aux["delta"])
    ev2 = fresh.evaluate(theta1)
    assert all(pm["kernel_status"] == "ok" and pm["stages"].startswith("warm") for pm in ev2.aux["per_market"])
    with pytest.raises(ValueError):
        fresh.model.load_state_dict(state | {"market_ids": ["9", "10"]})
    prob.model.close()
    fresh.model.close()


def test_max_step_hook(small: dict[str, Any]) -> None:
    prob = build_problem(small, THETA_TRUE)
    ev = prob.evaluate(THETA_TRUE)
    assert ev.ok and hasattr(prob, "max_step")
    lim = prob.max_step(ev, np.array([0.5, -0.5, 0.2, 0.3, 0.1]))
    assert isinstance(lim, StepLimit) and lim.tau_cap == 1.0
    assert lim.mass_profile.shape == (64, 2)
    assert lim.mass_profile[-1, 0] == pytest.approx(2.0)
    assert np.all(np.diff(lim.mass_profile[:, 1]) >= 0)
    assert 0.0 <= lim.tau_first <= lim.tau_vanish_lb <= 2.0
    prob.model.close()


