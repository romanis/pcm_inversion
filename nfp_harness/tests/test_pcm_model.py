def test_identical_across_thread_counts(small: dict[str, Any]) -> None:
    theta = THETA_TRUE + np.array([0.3, -0.4, 0.2, -0.3, 0.15])
    out = []
    for threads in (1, 16):
        prob = build_problem(small, theta, threads=threads)
        ev = prob.evaluate(theta)
        assert ev.ok
        out.append(ev)
        prob.model.close()
    assert out[0].aux["per_market"][0]["threads"] == 1 and out[1].aux["per_market"][0]["threads"] > 1
    np.testing.assert_array_equal(out[0].aux["delta"], out[1].aux["delta"])
    np.testing.assert_array_equal(out[0].g, out[1].g)
    np.testing.assert_array_equal(out[0].G, out[1].G)


def _petrin_frames() -> tuple[Any, Any]:
    if VENDOR.exists() and str(VENDOR) not in sys.path:
        sys.path.append(str(VENDOR))
    pyblp = pytest.importorskip("pyblp")
    pd = pytest.importorskip("pandas")
    products = pd.read_csv(pyblp.data.PETRIN_PRODUCTS_LOCATION)
    agents = pd.read_csv(pyblp.data.PETRIN_AGENTS_LOCATION)
    products["prices"] = break_price_ties(products.prices.to_numpy(float), products.market_ids.to_numpy(), 0.01)
    agents["logfs_fv"] = np.log(agents.fs) * agents.fv
    for lvl in ("low", "mid", "high"):
        agents[f"{lvl}_inc"] = agents[lvl] / agents.income
    return products, agents


def _petrin_layout() -> ParameterLayout:
    cols = ["const", "hpwt", "space", "air", "mpd", "fwd", "mi", "sw", "su", "pv"]
    starts = [3.0, 2.0, 1.0, 0.5, 1.0, 1.0, 2.0, 2.0, 2.0, 2.0]
    specs = [ParameterSpec(f"sigma_{c}", "taste", c, f"nu{k}", s, 0.0, 661.0, unit=1.0)
             for k, (c, s) in enumerate(zip(cols, starts))]
    specs += [ParameterSpec(f"pi_{c}", "taste", c, "logfs_fv", 0.3, -math.inf, math.inf, unit=1.0)
              for c in ("mi", "sw", "su", "pv")]
    specs += [ParameterSpec(f"phi_{lvl}", "scale", None, f"{lvl}_inc", 0.0, -math.inf, math.inf, unit=1.0)
              for lvl in ("low", "mid", "high")]
    specs.append(ParameterSpec("sigma_p", "sigma_p", None, None, 1.0, 0.05, 3.0))
    return ParameterLayout(specs)


def test_petrin_nu1_matches_python_pcm_demand() -> None:
    """One Petrin evaluation at nu_per_agent = 1 (1,024 draws per market) converges in all 13 markets,
    and its shares and deltas match python_pcm_demand.invert at the same theta."""
    products, agents = _petrin_frames()
    if not any(LEGACY_BINDINGS.glob("python_pcm_demand*.so")):
        pytest.skip("python_pcm_demand is not built in build-rel2")
    if str(LEGACY_BINDINGS) not in sys.path:
        sys.path.append(str(LEGACY_BINDINGS))
    import python_pcm_demand as legacy

    layout = _petrin_layout()
    chars = ("const", "hpwt", "space", "air", "mpd", "fwd", "mi", "sw", "su", "pv")
    tol = 1e-9
    model = PCMModel(PCMSpec(chars, tol=tol), {"products": products, "agents": agents}, layout, 1, 0)
    theta = layout.starts()
    sol = model.solve(theta, KernelRequests(), need_jacobian=True)
    assert sol.status is EvalStatus.OK, [pm["stages"] for pm in sol.per_market]
    assert len(sol.per_market) == 13 and all(pm["kernel_status"] == "ok" for pm in sol.per_market)
    assert all(m.R == 1024 for m in model._mk)
    s_data = products.shares.to_numpy(float)
    th, ph, sp = model.kernel_params(theta)

    def legacy_invert(t: int) -> tuple[np.ndarray, np.ndarray]:
        try:  # the legacy binding uses the calling thread's OpenMP team size; give each market a slice
            import ctypes
            ctypes.CDLL("libgomp.so.1").omp_set_num_threads(max(1, (os.cpu_count() or 1) // 13))
        except OSError:
            pass
        km = model.kernel_market(t)
        lm = legacy.Market(km.x, km.p, km.weights, km.taste_basis, km.taste_col, km.scale_basis)
        ref = legacy.invert(s_data[model.markets[t].rows], lm, th, ph, sp, np.empty(0), tol, 40000)
        assert ref["converged"]
        return ref["delta"], legacy.shares(ref["delta"], lm, th, ph, sp, False)["s"]

    with ThreadPoolExecutor(13) as pool:
        refs = list(pool.map(legacy_invert, range(13)))
    worst_s = worst_d = 0.0
    for m, (d_ref, s_ref) in zip(model.markets, refs):
        worst_s = max(worst_s, float(np.max(np.abs(sol.outputs["shares"][m.rows] - s_data[m.rows]))),
                      float(np.max(np.abs(s_ref - s_data[m.rows]))))
        worst_d = max(worst_d, float(np.max(np.abs(sol.delta[m.rows] - d_ref))))
    print(f"  Petrin nu=1: max |s - s_data| {worst_s:.2e}, max |delta - delta_legacy| {worst_d:.2e}")
    assert worst_s <= tol
    assert worst_d < 1e-5
    assert all(np.all(np.isfinite(D)) for D in sol.D)
    model.close()


