def test_recovers_true_theta(medium: dict[str, Any]) -> None:
    """The harness optimizer from a perturbed start recovers theta_true, class CONVERGED."""
    start = THETA_TRUE * np.array([1.3, 0.7, 1.4, 0.75, 1.3])
    prob = build_problem(medium, start, threads=16)
    W1 = prob.initial_weighting(start)
    res = minimize(prob, W1, OptimizerOptions(stage="recovery", max_iterations=200))
    print(f"\n  {'parameter':10s} {'true':>10s} {'start':>10s} {'estimate':>14s}")
    for name, a, b, c in zip(NAMES, THETA_TRUE, start, res.theta):
        print(f"  {name:10s} {a:10.4f} {b:10.4f} {c:14.8f}")
    print(f"  convergence {res.convergence.value}, q {res.q:.3e}, accepted {res.accepted_steps}, "
          f"evaluations {res.evaluations}, kink-limited {res.kink_limited_steps}, pg {res.projected_gradient:.2e}")
    assert res.convergence is ConvergenceClass.CONVERGED
    np.testing.assert_allclose(res.theta, THETA_TRUE, atol=1e-5)
    np.testing.assert_allclose(res.evaluation.aux["beta"], BETA_TRUE, atol=1e-5)
    prob.model.close()
