def test_allocate_threads() -> None:
    n = allocate_threads(np.array([1.0, 3.0, 4.0]), 16)
    assert n.tolist() == [2, 6, 8]
    n = allocate_threads(np.array([1.0, 1.0, 1.0]), 10)
    assert n.sum() == 10 and n.min() == 3
    assert allocate_threads(np.array([0.0, 1e9]), 4).tolist() == [1, 3]
    assert allocate_threads(np.array([np.nan, 0.0]), 4).tolist() == [2, 2]
    assert allocate_threads(np.ones(5), 3).tolist() == [1, 1, 1, 1, 1]


