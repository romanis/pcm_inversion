"""Tests for the PCM adapter (WP7; DESIGN 7 WP7 acceptance).

Synthetic data are generated by the model itself: characteristics, prices and agents are drawn at
random, delta = X1 beta + xi with xi orthogonal to Z in sample, and the data shares are the kernel's
shares at (delta, theta_true). Micro moment values are the model's predictions at theta_true. So
g(theta_true) = 0 exactly (up to the inversion tolerance) and theta_true is the GMM minimum.
"""

