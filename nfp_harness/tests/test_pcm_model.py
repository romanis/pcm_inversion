def central_fd(prob: NFPGMMProblem, theta: np.ndarray, delta0: np.ndarray) -> tuple[np.ndarray, list[float]]:
    """Central differences of g, with a step per parameter small enough that no draw's frontier
    changes between theta - h, theta and theta + h (the exact PCM has kinks where it does)."""
    model: PCMModel = prob.model
    sig0 = model.frontier_signatures(theta, delta0)
    cols, steps = [], []
    for k in range(theta.size):
        h = 1e-5 * max(1.0, abs(theta[k]))
        for _ in range(5):
            gs, same = [], True
            for sgn in (1.0, -1.0):
                th = theta.copy()
                th[k] += sgn * h
                ev = prob.evaluate(th, need_jacobian=False)
                prob.restore(th)
                assert ev.ok, ev.status
                gs.append(ev.g)
                sig = model.frontier_signatures(th, ev.aux["delta"])
                same &= all(np.array_equal(a, b) for a, b in zip(sig, sig0))
            if same:
                break
            h /= 10.0
        cols.append((gs[0] - gs[1]) / (2.0 * h))
        steps.append(h)
    return np.column_stack(cols), steps


def check_G(prob: NFPGMMProblem, theta: np.ndarray, tol: float) -> float:
    ev = prob.evaluate(theta)
    assert ev.ok, ev.status
    prob.commit(theta)
    fd, steps = central_fd(prob, theta, ev.aux["delta"])
    rel = [float(np.max(np.abs(ev.G[:, k] - fd[:, k])) / max(np.max(np.abs(ev.G[:, k])), 1e-12))
           for k in range(theta.size)]
    for name, h, r in zip(NAMES, steps, rel):
        print(f"  {name:10s} h {h:.0e}  max relative error {r:.3e}")
    assert max(rel) < tol, rel
    return max(rel)


